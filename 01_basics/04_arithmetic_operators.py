#5 /= (Division assignment)
x = 6
x /= 3       # x = x / 3
print("/= :", x)  # 2.0

#6 %= (Modulus assignment)
x = 5
x %= 3       # x = x % 3
print("%= :", x)  # 2

#7 //= (Floor division assignment)
x = 7
x //= 3      # x = x // 3
print("//= :", x)  # 2

#8 **= (Exponentiation assignment)
x = 2
x **= 3      # x = x ** 3
print("**= :", x)  # 8

# &= (bitwise and assignment operator)
